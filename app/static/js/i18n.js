window.QAS_t = function (lang, key, vars) {
  var pack = window.QAS_I18N[lang] || window.QAS_I18N.zh;
  var s = pack[key] || window.QAS_I18N.zh[key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (k) {
      s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return s;
};

window.QAS_applyHtmlLang = function (lang) {
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
};
